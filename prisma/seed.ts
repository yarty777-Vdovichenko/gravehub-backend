async function main() {
  console.log('Заповнення послуг...');
  for (const s of services) {
    await prisma.service.upsert({
      where: { id: s.id },
      update: {},
      create: s,
    });
  }

  console.log('Заповнення регіонів...');
  for (const r of regions) {
    await prisma.region.upsert({
      where: { id: r.id },
      update: {},
      create: r,
    });
  }

  console.log('Готово!');
}

